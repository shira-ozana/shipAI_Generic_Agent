"""apply_harness: validate planned paths, write Markdown under platform/, check links (no LLM)."""

from __future__ import annotations

import re
from pathlib import Path, PurePosixPath

from ..models import PlannedFile, WriteResult

BEGIN = "<!-- init-agent:begin (generated by INIT; edit outside this block) -->"
END = "<!-- init-agent:end -->"
_BLOCK_RE = re.compile(re.escape(BEGIN.split(" (")[0]) + r".*?" + re.escape(END), re.DOTALL)

CATALOG = {"AGENTS.md", "ARCHITECTURE.md", "RULES.md", "GUIDELINES.md", "DEVELOPMENT.md", "TESTING.md", "HOOKS.md",
           "TOOLS.md", "GUARDRAILS.md", "DOMAIN.md", "CONTRACTS.md"}
_SLUG = r"[a-z0-9][a-z0-9-]{0,62}"
_ALLOWED = [
    re.compile(r"^(" + "|".join(re.escape(n) for n in CATALOG) + r")$"),
    re.compile(rf"^skills/{_SLUG}/SKILL\.md$"),
    re.compile(rf"^adr/{_SLUG}\.md$"),
    re.compile(r"^areas/[A-Za-z0-9_.@()\[\]/-]+/AGENTS\.md$"),
]
_LINK_RE = re.compile(r"\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")


class PathRejected(ValueError):
    pass


def normalize(path: str, platform_dir: str) -> str:
    p = path.strip().replace("\\", "/")
    while p.startswith("./"):
        p = p[2:]
    if p.startswith(platform_dir + "/"):
        p = p[len(platform_dir) + 1:]
    return p


def validate(path: str, root: Path, platform_dir: str) -> Path:
    """Return the absolute target, or raise PathRejected."""
    pp = PurePosixPath(path)
    if pp.is_absolute() or ".." in pp.parts or ":" in path:
        raise PathRejected(f"path escapes the working copy: {path}")
    if not any(rx.match(path) for rx in _ALLOWED):
        raise PathRejected(f"not a harness file from the catalog: {path}")
    base = (root / platform_dir).resolve()
    target = (base / path).resolve()
    if base not in target.parents:
        raise PathRejected(f"path resolves outside {platform_dir}/: {path}")
    return target


def _merge(existing: str, content: str) -> tuple[str, str]:
    block = f"{BEGIN}\n{content.rstrip()}\n{END}"
    if _BLOCK_RE.search(existing):
        return _BLOCK_RE.sub(lambda _: block, existing, count=1), "replaced the generated block; human content kept"
    return existing.rstrip() + "\n\n" + block + "\n", "appended a generated block; human content kept"


def write_file(root: Path, platform_dir: str, f: PlannedFile, dry_run: bool) -> WriteResult:
    rel = f"{platform_dir}/{f.path}"
    try:
        target = validate(f.path, root, platform_dir)
    except PathRejected as exc:
        return WriteResult(path=rel, action="failed", detail=str(exc))
    if f.action == "keep":
        return WriteResult(path=rel, action="kept" if target.exists() else "skipped",
                           detail="" if target.exists() else "keep requested but file does not exist")
    if not (f.content or "").strip():
        return WriteResult(path=rel, action="failed", detail="no content was drafted")
    if dry_run:
        return WriteResult(path=rel, action="planned", bytes=len(f.content.encode()))
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            text, detail = _merge(target.read_text(encoding="utf-8"), f.content)
            action = "updated"
        else:
            text, detail = f"{BEGIN}\n{f.content.rstrip()}\n{END}\n", ""
            action = "created"
        target.write_text(text, encoding="utf-8", newline="\n")
        return WriteResult(path=rel, action=action, detail=detail, bytes=len(text.encode()))
    except OSError as exc:
        return WriteResult(path=rel, action="failed", detail=f"write error: {exc.strerror or exc}")


def check_links(root: Path, md_paths: list[str]) -> list[str]:
    """Relative links in written files that do not resolve on disk."""
    broken: list[str] = []
    for rel in md_paths:
        file = root / rel
        if not file.is_file():
            continue
        for target in _LINK_RE.findall(file.read_text(encoding="utf-8")):
            if re.match(r"^(https?:|mailto:|#)", target):
                continue
            clean = target.split("#")[0]
            if not clean:
                continue
            resolved = (file.parent / clean).resolve()
            if not resolved.exists():
                broken.append(f"{rel} -> {target}")
    return broken
