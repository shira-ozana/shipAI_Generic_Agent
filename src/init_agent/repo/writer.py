"""apply_harness: validate planned paths, write Markdown into the repository, check links (no LLM).

Harness files go to the repository root (catalog files, `skills/`, `adr/`) and next to the
code (`<code-folder>/AGENTS.md`). `platform/` holds only the INIT report. Only catalog
Markdown names are accepted; application code, configs and CI files are never written.
"""

from __future__ import annotations

import re
from pathlib import Path, PurePosixPath

from ..models import PlannedFile, WriteResult
from .scanner import SKIP_DIRS

BEGIN = "<!-- init-agent:begin (generated by INIT; edit outside this block) -->"
END = "<!-- init-agent:end -->"
_BLOCK_RE = re.compile(re.escape(BEGIN.split(" (")[0]) + r".*?" + re.escape(END), re.DOTALL)

CATALOG = {"AGENTS.md", "ARCHITECTURE.md", "RULES.md", "GUIDELINES.md", "DEVELOPMENT.md", "TESTING.md", "HOOKS.md",
           "TOOLS.md", "GUARDRAILS.md", "DOMAIN.md", "CONTRACTS.md"}
_SLUG = r"[a-z0-9][a-z0-9-]{0,62}"
# Paths are relative to the repository root. Catalog files sit at the root, local
# AGENTS.md files sit next to the code they describe.
_ALLOWED = [
    re.compile(r"^(" + "|".join(re.escape(n) for n in CATALOG) + r")$"),
    re.compile(rf"^skills/{_SLUG}/SKILL\.md$"),
    re.compile(rf"^adr/{_SLUG}\.md$"),
]
_FOLDER = r"[A-Za-z0-9_.@()\[\]/-]+"
_LOCAL_AGENTS = re.compile(rf"^{_FOLDER}/AGENTS\.md$")
# A skill that belongs to one code folder: `<code-folder>/skills/<name>/SKILL.md`.
_LOCAL_SKILL = re.compile(rf"^({_FOLDER})/skills/{_SLUG}/SKILL\.md$")
_LINK_RE = re.compile(r"\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")


class PathRejected(ValueError):
    pass


def normalize(path: str, platform_dir: str) -> str:
    """Repository-relative path. Accepts the older `platform/...` and `areas/<folder>/AGENTS.md` forms."""
    p = path.strip().replace("\\", "/")
    while p.startswith("./"):
        p = p[2:]
    if p.startswith(platform_dir + "/"):
        p = p[len(platform_dir) + 1:]
    if p.startswith("areas/") and p.endswith("/AGENTS.md"):
        p = p[len("areas/"):]
    return p


def is_local_agents(path: str) -> bool:
    """`<code-folder>/AGENTS.md` (not the root one)."""
    return bool(_LOCAL_AGENTS.match(path)) and not path.startswith("skills/") and "/skills/" not in path


def is_skill_path(path: str) -> bool:
    """`skills/<name>/SKILL.md` at the root or `<code-folder>/skills/<name>/SKILL.md`."""
    return bool(_ALLOWED[1].match(path) or _LOCAL_SKILL.match(path))


def code_folder_of(path: str) -> str | None:
    """The code folder a local harness file belongs to; None for root files."""
    if is_local_agents(path):
        return str(PurePosixPath(path).parent)
    m = _LOCAL_SKILL.match(path)
    return m.group(1) if m else None


def is_harness_path(path: str) -> bool:
    return any(rx.match(path) for rx in _ALLOWED) or is_local_agents(path) or bool(_LOCAL_SKILL.match(path))


def validate(path: str, root: Path, platform_dir: str) -> Path:
    """Return the absolute target inside the repository, or raise PathRejected."""
    pp = PurePosixPath(path)
    if pp.is_absolute() or ".." in pp.parts or ":" in path:
        raise PathRejected(f"path escapes the working copy: {path}")
    if not is_harness_path(path):
        raise PathRejected(f"not a harness file from the catalog: {path}")
    if pp.parts[0] == platform_dir:
        raise PathRejected(f"{platform_dir}/ holds the INIT report only: {path}")
    base = root.resolve()
    target = (base / path).resolve()
    if base not in target.parents:
        raise PathRejected(f"path resolves outside the repository: {path}")
    folder = code_folder_of(path)
    if folder is not None:
        if not (base / folder).is_dir():
            raise PathRejected(f"local harness file needs an existing code folder: {folder}")
        if any(part in SKIP_DIRS or part.startswith(".") for part in PurePosixPath(folder).parts):
            raise PathRejected(f"not a source folder: {folder}")
    return target


def is_generated_only(text: str) -> bool:
    """True when the file holds nothing but INIT's managed block (no human content)."""
    m = _BLOCK_RE.search(text)
    return bool(m) and not (text[: m.start()] + text[m.end():]).strip()


def _merge(existing: str, content: str) -> tuple[str, str]:
    block = f"{BEGIN}\n{content.rstrip()}\n{END}"
    if _BLOCK_RE.search(existing):
        return _BLOCK_RE.sub(lambda _: block, existing, count=1), "replaced the generated block; human content kept"
    return existing.rstrip() + "\n\n" + block + "\n", "appended a generated block; human content kept"


def write_file(root: Path, platform_dir: str, f: PlannedFile, dry_run: bool) -> WriteResult:
    rel = f.path
    try:
        target = validate(f.path, root, platform_dir)
    except PathRejected as exc:
        return WriteResult(path=rel, action="failed", detail=str(exc))
    if f.action == "keep":
        return WriteResult(path=rel, action="kept" if target.exists() else "skipped",
                           detail="" if target.exists() else "keep requested but file does not exist")
    if not (f.content or "").strip():
        return WriteResult(path=rel, action="failed", detail="no content was drafted")
    if dry_run:
        return WriteResult(path=rel, action="planned", bytes=len(f.content.encode()))
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            text, detail = _merge(target.read_text(encoding="utf-8"), f.content)
            action = "updated"
        else:
            text, detail = f"{BEGIN}\n{f.content.rstrip()}\n{END}\n", ""
            action = "created"
        target.write_text(text, encoding="utf-8", newline="\n")
        return WriteResult(path=rel, action=action, detail=detail, bytes=len(text.encode()))
    except OSError as exc:
        return WriteResult(path=rel, action="failed", detail=f"write error: {exc.strerror or exc}")


def broken_targets(root: Path, rel: str, text: str, pending: list[str] = ()) -> list[str]:
    """Link targets in `text` (the body of repository file `rel`) that do not resolve.

    `pending` are repository paths written later in the run (the INIT report itself).
    """
    later = {(root / p).resolve() for p in pending}
    folder = (root / rel).parent
    out: list[str] = []
    for target in _LINK_RE.findall(text):
        if re.match(r"^(https?:|mailto:|#)", target):
            continue
        clean = target.split("#")[0]
        if not clean:
            continue
        resolved = (folder / clean).resolve()
        if not resolved.exists() and resolved not in later and target not in out:
            out.append(target)
    return out


def check_links(root: Path, md_paths: list[str], pending: list[str] = ()) -> list[str]:
    """Relative links in written files that do not resolve on disk."""
    broken: list[str] = []
    for rel in md_paths:
        file = root / rel
        if file.is_file():
            broken += [f"{rel} -> {t}" for t in broken_targets(root, rel, file.read_text(encoding="utf-8"), pending)]
    return broken


def generated_block(text: str) -> str | None:
    """The body INIT wrote inside its managed block, or None when there is no block."""
    m = _BLOCK_RE.search(text)
    if not m:
        return None
    block = m.group(0)[: -len(END)]              # drop the end marker
    _, _, body = block.partition("\n")            # drop the begin marker line
    return body.strip("\n")


def replace_generated_block(text: str, content: str) -> str:
    """Replace the managed block; content outside it (human-authored) is kept as is."""
    return _merge(text, content)[0]


def unlink(text: str, targets: list[str]) -> str:
    """Turn `[label](target)` into plain `label` for each target in `targets`."""
    bad = set(targets)

    def sub(m: re.Match) -> str:
        return m.group(1) if m.group(2) in bad else m.group(0)

    return re.sub(r"\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)", sub, text)
